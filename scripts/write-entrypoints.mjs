/**
 * Installs the root entry points after the tsup build.
 *
 * The published root must behave like cheerio 0.22.0: `require('cheerox')`
 * is the callable `cheerio` module (with `load`, `html`, `xml`, `text`,
 * `parseHTML`, `root`, `contains`, `version` and `fn` as its own
 * properties), while ESM imports get named exports plus the callable
 * default. tsup's namespace bundles cannot express that shape, so this
 * script writes dist/index.{cjs,mjs} and the declaration re-exports from
 * the legacy/modern bundles.
 */
import assert from 'node:assert/strict';
import { copyFileSync, existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const dist = fileURLToPath(new URL('../dist/', import.meta.url));

const namedLegacy = ['cheerio', 'load', 'html', 'xml', 'text', 'parseHTML', 'root', 'contains'];
const namedModern = [
  'loadAsync', 'loadAll', 'extractAll', 'configureWorkers', 'workerPoolInfo',
  'nativeStatus', 'dom', 'merge', 'flattenOptions', 'createAPI',
  'loadBuffer', 'stringStream', 'decodeStream', 'fromURL',
];

writeFileSync(dist + 'index.cjs', `'use strict';
const legacy = require('./legacy.cjs');
const modern = require('./modern.cjs');
const cheerio = legacy.cheerio || legacy.default;
// Cheerox's asynchronous extensions stay available additively.
for (const key of ${JSON.stringify(namedModern)}) {
  if (cheerio[key] === undefined) cheerio[key] = modern[key];
}
module.exports = cheerio;
module.exports.default = cheerio;
module.exports.legacyStatics = legacy.legacyStatics;
`);

writeFileSync(dist + 'index.mjs', `import legacy, {
  ${namedLegacy.join(',\n  ')},
} from './legacy.mjs';
import {
  ${namedModern.join(',\n  ')},
} from './modern.mjs';
export {
  ${[...namedLegacy, ...namedModern].join(',\n  ')},
};
export const legacyStatics = legacy.legacyStatics;
export const version = legacy.version;
export default legacy;
`);

// The declarations: CommonJS keeps the callable `export =` shape of the
// original module; ESM re-exports the named surface plus the callable
// default (generated by tsup and asserted below).
writeFileSync(dist + 'index.d.ts', `// NOTE: this file must remain a script (no top-level imports) so that the
// callable function+namespace merge resolves for CJS consumers.
declare function cheerio(selector?: any, context?: any, root?: any, options?: any): import('./legacy.js').CheerioInstance;
declare namespace cheerio {
  export type CheerioInstance = import('./legacy.js').CheerioInstance;
  export type CheerioConstructor = import('./legacy.js').CheerioConstructor;
  export type CheerioStatic = import('./legacy.js').CheerioStatic;
  export type CheerioPrototype = import('./legacy.js').CheerioPrototype;
  export type LegacyNode = import('./legacy.js').LegacyNode;
  export type LegacyOptions = import('./legacy.js').LegacyOptions;
  export function load(content: string | Buffer | ArrayLike<LegacyNode> | LegacyNode, options?: LegacyOptions | null): CheerioStatic;
  export function html(dom?: any, options?: LegacyOptions): string;
  export function xml(dom?: any): string;
  export function text(elems?: ArrayLike<LegacyNode>): string;
  export function parseHTML(data?: string | null, context?: unknown, keepScripts?: boolean): LegacyNode[] | null;
  export function root(): CheerioInstance;
  export function contains(container?: LegacyNode, contained?: LegacyNode): boolean;
  export const version: string;
  export const fn: CheerioPrototype;
  export const prototype: CheerioPrototype;
  export const loadAsync: typeof import('./modern.js').loadAsync;
  export const loadAll: typeof import('./modern.js').loadAll;
  export const extractAll: typeof import('./modern.js').extractAll;
  export const configureWorkers: typeof import('./modern.js').configureWorkers;
  export const workerPoolInfo: typeof import('./modern.js').workerPoolInfo;
}

export = cheerio;
`);

// A real CommonJS declaration twin: importing the .cjs directly resolves
// index.d.cts, not the exports map.
copyFileSync(dist + 'index.d.ts', dist + 'index.d.cts');

// tsdown emits CJS declarations as .d.cts; publish .d.ts twins so tooling
// that assumes a plain .d.ts still resolves the CJS-flavored declarations.
for (const name of readdirSync(dist).filter((file) => file.endsWith('.d.cts'))) {
  const twin = dist + name.slice(0, -6) + '.d.ts';
  if (name === 'index.d.cts') continue; // the hand-written export= declaration wins
  copyFileSync(dist + name, twin);
}

assert.match(readFileSync(dist + 'index.d.ts', 'utf8'), /export = cheerio;/, 'index.d.ts must declare the callable export=');
assert.match(readFileSync(dist + 'index.d.ts', 'utf8'), /declare function cheerio/, 'index.d.ts must declare the callable function');
for (const extension of ['d.mts']) {
  const source = readFileSync(dist + 'index.' + extension, 'utf8');
  assert.match(source, /\bload\b/, 'index declaration must export the legacy statics');
  assert.match(source, /(export default|as default)/, 'index declaration must export the callable default');
}

// The internal legacy parse module: a callable `parse` with `evaluate` and
// `update` attached, as cheerio 0.22.0's lib/parse.js exposed.
writeFileSync(dist + 'legacy-parse.cjs', `'use strict';
const legacy = require('./legacy.cjs');
module.exports = legacy.parse;
module.exports.evaluate = legacy.evaluate;
module.exports.update = legacy.update;
`);

writeFileSync(dist + 'legacy-parse.mjs', `export { parse as default, evaluate, update, parse } from './legacy.mjs';
`);

writeFileSync(dist + 'legacy-parse.d.ts', `import type { LegacyNode, LegacyOptions } from './legacy.js';
declare function parse(content: string | Buffer, options?: LegacyOptions | null): LegacyNode;
declare namespace parse {
  export function evaluate(content: string | Buffer, options?: LegacyOptions | null): LegacyNode[];
  export function update(arr: unknown, parent: LegacyNode | null): LegacyNode | null;
}
export = parse;
`);

writeFileSync(dist + 'legacy-parse.d.mts', `import type { LegacyNode, LegacyOptions } from './legacy.js';
declare function parse(content: string | Buffer, options?: LegacyOptions | null): LegacyNode;
declare namespace parse {
  export function evaluate(content: string | Buffer, options?: LegacyOptions | null): LegacyNode[];
  export function update(arr: unknown, parent: LegacyNode | null): LegacyNode | null;
}
export default parse;
export { evaluate, update, parse };
`);

console.log('Root entry points installed (callable CommonJS, named-export ESM).');
